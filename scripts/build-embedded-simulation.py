"""Build the in-app renderer from the shared simulation source, without an iframe."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1];src=root/'dist/prototipe-simulasi';dest=root/'dist'
s=(src/'app.js').read_text()
# Use a separate dialog, live region, and scoped host; preserve the exam engine.
s=s.replace("'#dialog'","'#simulation-dialog'").replace('id="dialog-title"','id="simulation-dialog-title"').replace("'#announce'","'#simulation-announce'")
s=s.replace("+actions+'</div>'","+qualifyHandlers(actions)+'</div>'")
a=s.index('function prototypeHeader(');b=s.index('\nfunction sources()',a)
s=s[:a]+'''function prototypeHeader(step){return window.GakuSimulationHost.title('Simulasi',step===0?'Latihan ujian, satu langkah lebih siap.':EXAMS[state.exam].name+' · '+packLabel())+'<main class="shell">'}
'''+s[b:]
# The shared page header already provides Back; remove the duplicate narrow back buttons.
s=s.replace(r"""<button class="back" onclick="go(\'menu\')">← Jenis simulasi</button>""",'')
s=s.replace(r"""<button class="back" onclick="go(\'packages\')">← Paket soal</button>""",'')
# Host owns DOM rendering and tab lifecycle. Interval is managed separately.
a=s.index('function render(){');s=s[:a]+'''function render(){persist();if(window.GakuSimulationHost.active())window.GakuSimulationHost.render();syncLifecycle()}
'''
names=re.findall(r'^function (\w+)\(',s,re.M)
bridge=(root/'scripts/embedded-simulation-bridge.js').read_text().replace('__EXPORTED_FUNCTIONS__',','.join(names))
out='/* Generated by scripts/build-embedded-simulation.py. Shared simulation engine, isolated scope. */\n(function(){\nwindow.GAKU_SIM_EMBEDDED=true;\n'+s+'\n'+bridge+'\n})();\n'
(dest/'simulation-module.js').write_text(out)
css=(src/'style.css').read_text()
def scoped(sel):
 sel=sel.strip().replace('+aside','+section')
 if ':root' in sel:return sel.replace(':root','.simulation-module')
 if re.match(r'^body\b',sel):return re.sub(r'^body','.simulation-module',sel)
 return '.simulation-module '+sel
# This stylesheet uses qualified rules and @media only. Walk balanced blocks.
def transform(text):
 result='';i=0
 while i<len(text):
  start=text.find('{',i)
  if start<0:result+=text[i:];break
  header=text[i:start];j=start+1;depth=1
  while depth:
   if text[j]=='{':depth+=1
   elif text[j]=='}':depth-=1
   j+=1
  body=text[start+1:j-1]
  if header.strip().startswith('@media'):result+=header+'{'+transform(body)+'}'
  else:result+=','.join(scoped(x) for x in header.split(','))+'{'+body+'}'
  i=j
 return result
css=transform(css)
# Preserve main app typography, theme and page background; supply exam-specific tokens only.
a=css.index('{');b=css.index('}',a)
css=css[:a+1]+'''--teal:var(--green);--purple:#9271b4;--mint:#eaf3ee;--orange:#b87631;--soft:#f0eafb;font-size:17px;color:var(--ink);font-family:inherit;'''+css[b:]
css+='\n'+(root/'scripts/embedded-simulation-overrides.css').read_text()
(dest/'simulation-module.css').write_text('/* Scoped to the Simulasi menu; generated from the shared stylesheet. */\n'+css)
print('Generated native simulation module and scoped styles')
